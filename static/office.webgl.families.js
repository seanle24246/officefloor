export function familyForFixture(fixture) {
  const kind = String(fixture?.kind || fixture?.type || '').trim().toLowerCase();
  return FIXTURE_FAMILY_OVERRIDES[kind] || null;
}

export function familyForSku(item) {
  const sku = String(item?.sku_id || item?.sku || '');
  const category = String(item?.source?.category ?? item?.category ?? '').trim().toLowerCase();
  const family = SKU_FAMILY_OVERRIDES[sku] || NORMALIZED_CATEGORY_FAMILIES.get(category);
  if (!FAMILY_SET.has(family)) {
    throw new TypeError(`unsupported WebGL family for ${sku || '<missing sku>'}`);
  }
  return family;
}

export const familyFor = familyForSku;

export function mapCatalogFamilies(catalog) {
  const items = Array.isArray(catalog) ? catalog : catalog?.items;
  if (!Array.isArray(items)) throw new TypeError('catalog items are required');
  return Object.freeze(Object.fromEntries(items.map((item) => [item.sku_id, familyForSku(item)])));
}
