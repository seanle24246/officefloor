"""Generate static/office.wardrobe.catalog.js from data/wardrobe-catalog.json (PKT:of-wardrobe-01).

Usage: python3 tools/gen_wardrobe_catalog_js.py          # write the file
       python3 tools/gen_wardrobe_catalog_js.py --check  # exit 1 (and print a unified diff) when it is stale
Stdlib only. The output is exactly TEMPLATE with {catalog} = json.dumps(catalog, separators=(',', ':'),
ensure_ascii=False, sort_keys=False) and {digest} = server.wardrobe.catalog_digest(catalog).
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from server import wardrobe  # noqa: E402

OUT = ROOT / "static" / "office.wardrobe.catalog.js"
TEMPLATE = """/* office.wardrobe.catalog.js — GENERATED by tools/gen_wardrobe_catalog_js.py from data/wardrobe-catalog.json.
   PKT:of-wardrobe-01. Do not edit by hand; run the generator. */
(function (root) {{
  'use strict';
  const CATALOG = Object.freeze(/*CATALOG*/{catalog}/*END*/);
  const DIGEST = '{digest}';
  const api = Object.freeze({{ CATALOG, DIGEST }});
  if (typeof module === 'object' && module.exports) module.exports = api;
  else (root.OFFICE ||= {{}}).wardrobeCatalog = api;
}})(typeof globalThis !== 'undefined' ? globalThis : this);
"""


def render() -> str:
    """The full generated file text."""
    catalog = wardrobe.load_catalog()
    return TEMPLATE.format(
        catalog=json.dumps(catalog, separators=(",", ":"), ensure_ascii=False, sort_keys=False),
        digest=wardrobe.catalog_digest(catalog),
    )


def main(argv: list[str]) -> int:
    """Write OUT, or with --check compare and return 1 with a diff on stdout when stale."""
    import difflib

    expected = render()
    if "--check" in argv:
        existing = OUT.read_text() if OUT.exists() else ""
        if existing == expected:
            return 0
        for line in difflib.unified_diff(existing.splitlines(), expected.splitlines(),
                                         fromfile=str(OUT), tofile=str(OUT) + ".expected", lineterm=""):
            print(line)
        return 1
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(expected)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
